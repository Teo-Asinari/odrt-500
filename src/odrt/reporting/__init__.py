"""Render generated reports (markdown + PNG) from simulation results.

Output is deterministic for a given input hash and environment, so `make ci`
can fail when committed reports are stale.
"""
from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from odrt.components import tension_capability_lbf  # noqa: E402
from odrt.drivetrain import RPM_PER_RAD_S, solve  # noqa: E402
from odrt.scenarios import Trajectory, settle_s  # noqa: E402
from odrt.units import n_to_lbf  # noqa: E402

DISCLAIMER = ("> Generated by `make report`. Do not edit by hand. These are abstract simulation "
              "inputs and idealised metrics, not certification, not proof of feasibility, and not "
              "exercise or human-use guidance.")

FOCUS_SCENARIO = "heavy_tempo_limit"
DYN_FIGURE_CASES = ("tracking_heavy_tempo", "tracking_low_force", "release_at_500lbf_speed_limit",
                    "power_loss_shorted_mid_pull")


def _slug(text: str) -> str:
    return "".join(ch if ch.isalnum() else "_" for ch in text)
ARCH_COLORS = ["#4c6a92", "#a0524d", "#6a8f6b"]
COLORS = {"x": "#4c6a92", "v": "#6a8f6b", "f": "#a0524d", "p": "#8a6a9f"}


def write_reports(inputs, payload: dict, sim_dir: Path, out: Path, structure: dict = None):
    out = Path(out)
    (out / "figures").mkdir(parents=True, exist_ok=True)
    written = []
    for name, scenario in inputs.scenarios.items():
        path = out / "figures" / f"{name}.png"
        _plot_scenario(scenario, inputs.defaults, np.load(sim_dir / f"{name}.npz"), path)
        written.append(path)
    written.append(_write_text(out / "duty_cycles.md", _duty_cycles_md(inputs, payload)))
    written.append(_write_text(out / "drivetrain_baseline.md", _drivetrain_md(inputs, payload)))
    path = out / "figures" / f"drivetrain_{FOCUS_SCENARIO}.png"
    _plot_drivetrain(inputs, np.load(sim_dir / f"{FOCUS_SCENARIO}.npz"), path)
    written.append(path)
    written.append(_write_text(out / "components.md", _components_md(inputs, payload)))
    written.append(_write_text(out / "thermal.md", _thermal_md(inputs, payload)))
    written.append(_write_text(out / "dynamics.md", _dynamics_md(inputs, payload)))
    for case in DYN_FIGURE_CASES:
        design = inputs.dynamics.designs[0]
        path = out / "figures" / f"dyn_{case}.png"
        _plot_dynamics(design, case, np.load(sim_dir / f"dyn__{_slug(design)}__{case}.npz"), path)
        written.append(path)
    if structure is not None:
        written.append(_write_text(out / "structure.md", _structure_md(inputs, structure)))
    written.append(_write_text(out / "hazards.md", _hazards_md(inputs, payload)))
    written.append(_write_text(out / "economics.md", _economics_md(inputs)))
    written.append(_write_text(out / "traceability.md", _traceability_md(inputs)))
    written.append(_write_text(out / "assumptions.md", _assumptions_md(inputs)))
    return written


def _write_text(path: Path, text: str) -> Path:
    path.write_text(text)
    return path


def _header(title: str, inputs) -> list:
    return [f"# {title}", "", DISCLAIMER, "",
            f"Input hash: `{inputs.input_hash[:16]}`", ""]


