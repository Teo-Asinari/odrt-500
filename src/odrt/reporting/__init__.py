"""Render generated reports (markdown + PNG) from simulation results.

Output is deterministic for a given input hash and environment, so `make ci`
can fail when committed reports are stale.
"""
from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from odrt.drivetrain import RPM_PER_RAD_S, solve  # noqa: E402
from odrt.scenarios import Trajectory, settle_s  # noqa: E402
from odrt.units import n_to_lbf  # noqa: E402

DISCLAIMER = ("> Generated by `make report`. Do not edit by hand. These are abstract simulation "
              "inputs and idealised metrics, not certification, not proof of feasibility, and not "
              "exercise or human-use guidance.")

FOCUS_SCENARIO = "heavy_tempo_limit"
ARCH_COLORS = ["#4c6a92", "#a0524d", "#6a8f6b"]
COLORS = {"x": "#4c6a92", "v": "#6a8f6b", "f": "#a0524d", "p": "#8a6a9f"}


def write_reports(inputs, payload: dict, sim_dir: Path, out: Path):
    out = Path(out)
    (out / "figures").mkdir(parents=True, exist_ok=True)
    written = []
    for name, scenario in inputs.scenarios.items():
        path = out / "figures" / f"{name}.png"
        _plot_scenario(scenario, inputs.defaults, np.load(sim_dir / f"{name}.npz"), path)
        written.append(path)
    written.append(_write_text(out / "duty_cycles.md", _duty_cycles_md(inputs, payload)))
    written.append(_write_text(out / "drivetrain_baseline.md", _drivetrain_md(inputs, payload)))
    path = out / "figures" / f"drivetrain_{FOCUS_SCENARIO}.png"
    _plot_drivetrain(inputs, np.load(sim_dir / f"{FOCUS_SCENARIO}.npz"), path)
    written.append(path)
    written.append(_write_text(out / "traceability.md", _traceability_md(inputs)))
    written.append(_write_text(out / "assumptions.md", _assumptions_md(inputs)))
    return written


def _write_text(path: Path, text: str) -> Path:
    path.write_text(text)
    return path


def _header(title: str, inputs) -> list:
    return [f"# {title}", "", DISCLAIMER, "",
            f"Input hash: `{inputs.input_hash[:16]}`", ""]


def _duty_cycles_md(inputs, payload) -> str:
    lines = _header("WP1 duty cycles", inputs)
    prov = payload["provenance"]
    lines += [f"Generated with odrt {prov['odrt_version']}, Python {prov['python']}, "
              f"NumPy {prov['numpy']}. Sample rate {inputs.defaults.sample_rate_hz:g} Hz, "
              f"tension ramp {inputs.defaults.tension_ramp_s:g} s, rest tension "
              f"{inputs.defaults.rest_tension_lbf:g} lbf, under-tension threshold "
              f"{inputs.defaults.tut_threshold_lbf:g} lbf.", "",
              "Power sign: absorbed = device takes energy from the cable (extension); "
              "returned = device gives energy back (retraction). RMS tension is a copper-loss "
              "proxy only (A-006).", "",
              "| Scenario | Kind | Duration s | Peak lbf | RMS lbf | Peak ext. m/s | Peak ret. m/s "
              "| Peak \\|a\\| m/s² | Peak absorbed W | Peak returned W | Absorbed kJ | Returned kJ "
              "| TUT s | Longest ≥95% peak s |",
              "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for name, s in inputs.scenarios.items():
        m = payload["scenarios"][name]
        lines.append(
            f"| [{name}](#{name}) | {s.kind} | {m['duration_s']:.1f} "
            f"| {m['peak_tension_lbf']:.0f} | {m['rms_tension_lbf']:.0f} "
            f"| {m['peak_extension_speed_m_s']:.2f} | {m['peak_retraction_speed_m_s']:.2f} "
            f"| {m['peak_abs_accel_m_s2']:.1f} | {m['peak_power_absorbed_w']:.0f} "
            f"| {m['peak_power_returned_w']:.0f} | {m['energy_absorbed_j'] / 1e3:.1f} "
            f"| {m['energy_returned_j'] / 1e3:.1f} | {m['time_under_tension_s']:.0f} "
            f"| {m['longest_near_peak_tension_s']:.1f} |")
    lines.append("")
    for name, s in inputs.scenarios.items():
        lines += [f"## {name}", "", s.description, "",
                  f"- Requirements: {', '.join(s.requirements)}",
                  f"- Assumptions: {', '.join(s.assumptions)}",
                  f"- Stroke {s.stroke_m:g} m from {s.start_offset_m:g} m; per rep: extend "
                  f"{s.extend_s:g} s, top hold {s.top_hold_s:g} s, retract {s.retract_s:g} s, "
                  f"bottom hold {s.bottom_hold_s:g} s; {s.reps} reps x {s.sets} sets, "
                  f"rest {s.rest_s:g} s",
                  f"- Tension setpoint: {s.extension_tension_lbf:g} lbf extension, "
                  f"{s.retraction_tension_lbf:g} lbf retraction", "",
                  f"![{name}](figures/{name}.png)", ""]
    return "\n".join(lines)


def _traceability_md(inputs) -> str:
    lines = _header("Requirements traceability", inputs)
    lines += ["| ID | Requirement | Status | Scenarios | Assumptions |", "|---|---|---|---|---|"]
    for rid, r in inputs.requirements.items():
        scen = [n for n, s in inputs.scenarios.items() if rid in s.requirements]
        asm = [a for a, v in inputs.assumptions.items() if rid in v.affects]
        lines.append(f"| {rid} | {r.title}: {r.target} | {r.status} "
                     f"| {', '.join(scen) or '—'} | {', '.join(asm) or '—'} |")
    lines.append("")
    return "\n".join(lines)


def _assumptions_md(inputs) -> str:
    lines = _header("Assumptions register", inputs)
    lines += ["Source of truth: `requirements/assumptions.yaml`.", "",
              "| ID | Statement | Basis | Confidence | Status | Affects |", "|---|---|---|---|---|---|"]
    for aid, a in inputs.assumptions.items():
        lines.append(f"| {aid} | {a.statement} | {a.basis} | {a.confidence} | {a.status} "
                     f"| {', '.join(a.affects)} |")
    lines.append("")
    return "\n".join(lines)


def _plot_scenario(scenario, defaults, data, path: Path) -> None:
    t, x, v, f = data["t"], data["x"], data["v"], data["tension_n"]
    p = f * v
    f_lbf = n_to_lbf(f)
    shown_reps = min(scenario.reps, 3)
    t_end = settle_s(defaults) + defaults.tension_ramp_s + shown_reps * scenario.cycle_s()
    zoom = t <= t_end
    step = max(1, len(t) // 20000)

    fig, axes = plt.subplots(5, 1, figsize=(8, 9.5), constrained_layout=True)
    fig.suptitle(f"{scenario.name} ({scenario.kind}) — illustrative simulation input", fontsize=11)
    ax = axes[0]
    ax.plot(t[::step], f_lbf[::step], color=COLORS["f"], lw=0.8)
    ax.set_title("Whole session: tension setpoint", fontsize=9, loc="left")
    ax.set_ylabel("lbf")
    ax.set_xlabel("time (s)")
    rows = [(x, "cable out (m)", "x"), (v, "speed (m/s)", "v"), (f_lbf, "tension (lbf)", "f"),
            (p, "power in (W)", "p")]
    for ax, (y, label, key) in zip(axes[1:], rows):
        ax.plot(t[zoom], y[zoom], color=COLORS[key], lw=1.2)
        ax.set_ylabel(label)
        ax.axhline(0, color="#999999", lw=0.5)
    axes[1].set_title(f"First {shown_reps} rep(s)", fontsize=9, loc="left")
    axes[-1].set_xlabel("time (s)")
    for ax in axes:
        ax.grid(True, color="#e4e4e4", lw=0.5)
        ax.tick_params(labelsize=8)
        for side in ("top", "right"):
            ax.spines[side].set_visible(False)
    fig.savefig(path, dpi=110, metadata={"Software": None})
    plt.close(fig)


def _drivetrain_md(inputs, payload) -> str:
    lines = _header("WP2 drivetrain baseline (illustrative architectures)", inputs)
    c = inputs.common
    lines += ["What each **illustrative** architecture (A-008) would demand of a motor and power stage "
              "for each duty cycle. A rigid lumped model (A-009) with copper loss only (A-010), evaluated "
              f"at {c.winding_temp_c:g} °C. Thermal figures are worst {c.thermal_window_s:g} s moving-window "
              "values (A-012). No motor is selected, so nothing here says any architecture is feasible.", "",
              "## Architectures", "",
              "| Architecture | Ratio | η | Drum radius m | Drum width mm | Inertia at drum kg·m² "
              "| Effective cable mass kg | Km@25 °C N·m/√W |", "|---|---:|---:|---|---:|---:|---:|---:|"]
    first = next(iter(inputs.scenarios))
    for name, a in inputs.architectures.items():
        m = payload["drivetrain"][name][first]
        full = payload["drivetrain"][name].get("full_stroke_limit", m)
        lines.append(f"| {name}: {a.description} | {a.gear_ratio:g} | {a.gear_efficiency:g} "
                     f"| {full['radius_min_m']:.4f}–{full['radius_max_m']:.4f} "
                     f"| {a.turns_per_layer * c.cable_diameter_m * 1e3:.0f} | {a.inertia_at_drum():.4f} "
                     f"| {full['effective_cable_mass_kg']:.0f} | {a.motor_km_nm_per_sqrt_w:g} |")
    lines += ["", "Bus power excludes drive and PSU losses (A-010). *Buffer at mean draw* is the "
              "lossless energy storage that would let the supply deliver only the session-mean power, "
              "absorbing regeneration and covering peaks. Without storage, the supply must deliver the "
              "peak draw and a dump load must absorb the peak regen.", "",
              "Effective cable mass is the rotating inertia felt at the cable, J/r², at the smallest "
              "radius. The controller must supply extra torque to hide it during fast changes (R-04).", ""]
    cols = [("peak_motor_torque_nm", "Peak motor N·m", ".1f"),
            ("worst_window_rms_motor_torque_nm", "Worst-window RMS N·m", ".1f"),
            ("peak_motor_speed_rpm", "Peak rpm", ".0f"),
            ("peak_copper_w", "Peak copper W", ".0f"),
            ("worst_window_copper_w", "Worst-window copper W", ".0f"),
            ("peak_bus_draw_w", "Peak bus draw W", ".0f"),
            ("peak_regen_w", "Peak regen W", ".0f"),
            ("regen_energy_kj", "Regen kJ", ".1f"),
            ("mean_bus_w", "Mean bus W", ".0f"),
            ("buffer_at_mean_draw_kj", "Buffer at mean draw kJ", ".1f")]
    for scen_name in inputs.scenarios:
        lines += [f"## {scen_name}", "", "| Architecture | " + " | ".join(h for _, h, _ in cols) + " |",
                  "|---|" + "---:|" * len(cols)]
        for name in inputs.architectures:
            m = payload["drivetrain"][name][scen_name]
            lines.append(f"| {name} | " + " | ".join(format(m[k], f) for k, _, f in cols) + " |")
        lines.append("")
    lines += [f"![drivetrain]({'figures/drivetrain_' + FOCUS_SCENARIO + '.png'})", ""]
    return "\n".join(lines)


def _plot_drivetrain(inputs, data, path: Path) -> None:
    traj = Trajectory(t=data["t"], x=data["x"], v=data["v"], a=data["a"],
                      tension_n=data["tension_n"], phase=data["phase"])
    scenario = inputs.scenarios[FOCUS_SCENARIO]
    t_end = settle_s(inputs.defaults) + inputs.defaults.tension_ramp_s + 2 * scenario.cycle_s()
    zoom = traj.t <= t_end
    t = traj.t[zoom]
    fig, axes = plt.subplots(4, 1, figsize=(8, 8), constrained_layout=True, sharex=True)
    fig.suptitle(f"{FOCUS_SCENARIO}: illustrative architectures (A-008), first 2 reps", fontsize=11)
    for color, (name, arch) in zip(ARCH_COLORS, inputs.architectures.items()):
        sig = solve(traj, arch, inputs.common, inputs.envelope.max_usable_stroke_m)
        axes[0].plot(t, sig.motor_torque_nm[zoom], color=color, lw=1.2, label=name)
        axes[1].plot(t, sig.motor_speed_rad_s[zoom] * RPM_PER_RAD_S, color=color, lw=1.2)
        axes[2].plot(t, sig.copper_w[zoom], color=color, lw=1.2)
        axes[3].plot(t, sig.bus_w[zoom], color=color, lw=1.2)
    for ax, label in zip(axes, ["motor torque (N·m)", "motor speed (rpm)", "copper loss (W)",
                                "bus power (W)\n< 0 = regen"]):
        ax.set_ylabel(label, fontsize=9)
        ax.axhline(0, color="#999999", lw=0.5)
        ax.grid(True, color="#e4e4e4", lw=0.5)
        ax.tick_params(labelsize=8)
        for side in ("top", "right"):
            ax.spines[side].set_visible(False)
    axes[0].set_yscale("symlog", linthresh=1)
    axes[1].set_yscale("symlog", linthresh=10)
    axes[0].legend(fontsize=8, frameon=False)
    axes[-1].set_xlabel("time (s)")
    fig.savefig(path, dpi=110, metadata={"Software": None})
    plt.close(fig)
